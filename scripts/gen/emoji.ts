// Generates packages/bridge/src/emoji-data.ts: Mattermost emoji names and their Unicode code points, from
// emoji-datasource (MIT; notice in packages/bridge/third_party/emoji-datasource). Mattermost names system
// emoji with the same short names, and skin tones as `<name>_<tone>_skin_tone` (checked against 11.7).
// Run `pnpm gen:emoji` after changing the pinned emoji-datasource version.
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { repoRoot } from '../lib/env.ts';

interface Entry {
  unified: string;
  short_names: string[];
  skin_variations?: Record<string, { unified: string }>;
}

const require = createRequire(import.meta.url);
const { version } = require('emoji-datasource/package.json') as { version: string };
const entries = require('emoji-datasource/emoji.json') as Entry[];

const TONES: Record<string, string> = {
  '1F3FB': 'light_skin_tone',
  '1F3FC': 'medium_light_skin_tone',
  '1F3FD': 'medium_skin_tone',
  '1F3FE': 'medium_dark_skin_tone',
  '1F3FF': 'dark_skin_tone',
};

// Primary names first: the bridge maps a character back to the first name listed for it.
const rows: [string, string][] = [];
for (const entry of entries) for (const name of entry.short_names) rows.push([name, entry.unified]);
for (const entry of entries) {
  for (const [tone, variation] of Object.entries(entry.skin_variations ?? {})) {
    const suffix = TONES[tone];
    // Combinations of two tones (couples) have no single Mattermost name.
    if (!suffix) continue;
    for (const name of entry.short_names) rows.push([`${name}_${suffix}`, variation.unified]);
  }
}

const out = path.join(repoRoot, 'packages/bridge/src/emoji-data.ts');
const lines = rows.map(([name, unified]) => `  [${JSON.stringify(name)}, '${unified}'],`);
writeFileSync(
  out,
  `// Generated by \`pnpm gen:emoji\` from emoji-datasource ${version} (MIT, see packages/bridge/third_party/emoji-datasource).
// Do not edit. Each row is a Mattermost emoji name and its Unicode code points; primary names come first.
export const EMOJI_NAMES: readonly (readonly [string, string])[] = [
${lines.join('\n')}
];
`,
);
console.log(`Wrote ${rows.length} emoji names to ${path.relative(repoRoot, out)}`);
